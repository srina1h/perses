// Loop operations
for (let i = 0; i < 5; i++) {
    print("Loop iteration:", i);
}

// String operations
let message = "Hello, World!";
print("Original message:", message);
print("Message length:", message.length);
print("Uppercase:", message.toUpperCase());

// While loop
let counter = 0;
while (counter < 3) {
    print("Counter:", counter);
    counter++;
}
