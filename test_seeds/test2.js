// Function definitions and calls
function add(a, b) {
    return a + b;
}

function multiply(a, b) {
    return a * b;
}

let num1 = 7;
let num2 = 3;

print("Addition:", add(num1, num2));
print("Multiplication:", multiply(num1, num2));

// Conditional logic
if (num1 > num2) {
    print("num1 is greater than num2");
} else {
    print("num2 is greater than or equal to num1");
}
