// Simple arithmetic operations
let x = 10;
let y = 5;
let result = x + y;
print("Result:", result);

// Array operations
let arr = [1, 2, 3, 4, 5];
let sum = arr.reduce((a, b) => a + b, 0);
print("Array sum:", sum);

// Object operations
let obj = {name: "test", value: 42};
print("Object:", obj.name, obj.value);
